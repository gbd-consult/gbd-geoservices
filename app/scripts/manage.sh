#!/bin/sh
#
# manage.sh -- reload the app or restart the stack on the server, or run a
# manage.py subcommand in its app container.
#
#   ./manage.sh reload          the app only: new image, options.yaml, import
#   ./manage.sh restart         the whole stack: docker compose down, then up
#   ./manage.sh import de_sh    in the background, logging to data/import.log
#   ./manage.sh update de_sh    import, reload, renew the tile cache: for cron
#   ./manage.sh init-elevation  download the missing elevation tiles, then draw the contours
#   ./manage.sh key-add kiel --scopes tiles search
#                               generate a key with vaultwarden-send.sh, register it,
#                               print the Send link for the customer
#   ./manage.sh drop-cache      any other argument: a manage.py subcommand
#
# deploy.sh copies it next to docker-compose.yml on the server. deploy.sh
# only builds the image and copies files, and `import` writes a new schema
# beside the served one; the app takes them up when it is recreated. It
# compiles the styles for the newest import when it starts, so nothing here
# does. The tile cache is kept, except by `update`; `./manage.sh drop-cache`
# empties it.
#
# `reload` recreates the app and nothing else: postgres, pgbouncer and Caddy
# keep running with the configuration they have. A change to postgresql.conf,
# pg_hba.conf, pgbouncer.ini, the Caddyfile or postgres.env takes `restart`,
# which stops everything and starts it again -- `down` removes the old
# containers and their logs with them. Both return once the containers are
# started, not healthy: the app compiles the styles and loads its Map pool
# for minutes after that, which `docker compose logs -f app` shows.
#
# Everything but `import` runs in the foreground and writes to stdout.
# `import` runs for minutes to hours, so it runs detached in the app
# container (`exec -d`), where neither a dropped ssh connection nor a Ctrl-C
# reaches it, and returns at once. The import appends to data/import.log
# itself, under a line naming the run, and holds data/import.status while
# it runs; a second import refuses to start. `update` waits for the import
# and only if it succeeded reloads, empties the tile cache, waits for the
# app and pre-caches again, so a cron job needs nothing else.
#
# In the checkout (app/scripts/manage.sh) it drives the dev stack,
# docker-compose.local.yml, the same way.

set -eu

if [ $# -eq 0 ]; then
    echo "usage: $0 reload | restart | <manage.py subcommand> [args...]     e.g. $0 import de_sh" >&2
    exit 2
fi

cd "$(dirname "$0")"
SCRIPTS=$PWD
if [ -f ../../docker-compose.local.yml ]; then
    cd ../..
    export COMPOSE_FILE=docker-compose.local.yml
fi

# Docker creates a missing bind-mount source as root, and the dev app runs
# as the invoking user: without this it cannot write a download. Not -R:
# the tile cache under data/ can be millions of files.
data_writable() {
    owner=$(docker compose exec -T app sh -c 'echo "$(id -u):$(id -g)"')
    docker compose exec -T -u 0 app sh -c 'mkdir -p /data/downloads && chown "$1" /data /data/downloads' sh "$owner"
}

# -T: no terminal is attached under cron, and `exec` without it
# fails with "the input device is not a TTY".
manage_py() {
    data_writable
    docker compose exec -T app python tools/manage.py "$@"
}

import_background() {
    if [ -e data/import.status ]; then
        echo "warning: data/import.status exists: $(cat data/import.status)" >&2
    fi
    data_writable
    docker compose exec -d app python tools/manage.py "$@"
    echo "import started, tail -f $PWD/data/import.log to monitor"
}

reload() {
    # --no-deps: postgres and pgbouncer are left as they are. The app reads
    # options.yaml once, when it starts; `up` alone recreates it only for a
    # new image or environment.
    docker compose up -d --no-deps --force-recreate app
    echo "app recreated, docker compose logs -f app to monitor"
}

# The app answers /health only once it has compiled the styles for the
# new import and loaded its Map pool, which pre-cache needs.
ready() {
    tries=180
    until docker compose exec -T app python -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/health')" 2>/dev/null; do
        tries=$((tries - 1))
        if [ "$tries" -eq 0 ]; then
            echo "the app did not become ready in 30 minutes" >&2
            exit 1
        fi
        sleep 10
    done
}

# The tile cache is not keyed by import, so after a reload it holds the
# old data's tiles. Dropped after the reload, not before: the old server
# would cache old tiles again in between.
update() {
    manage_py import "$@"
    reload
    manage_py drop-cache "$1"
    ready
    manage_py pre-cache "$1"
}

# The key is generated by vaultwarden-send.sh, the one place keys are made,
# which also puts it into a Vaultwarden Send; it prints the key and then the
# link. The key stays in this shell: it reaches manage.py on stdin, and only
# the link is printed. The Send exists before the key is registered, so a
# refused registration leaves a link to a key that opens nothing.
key_add() {
    [ $# -gt 0 ] || { echo "usage: $0 key-add <name> [key-register options]" >&2; exit 2; }
    sent=$(bash "$SCRIPTS/vaultwarden-send.sh" --generate-key -n "API-Key $1")
    key=$(printf '%s\n' "$sent" | sed -n 1p)
    link=$(printf '%s\n' "$sent" | sed -n 2p)
    if [ -z "$key" ] || [ -z "$link" ]; then
        echo "vaultwarden-send.sh returned no key and link" >&2
        exit 1
    fi
    printf '%s\n' "$key" | manage_py key-register "$@"
    echo "$link"
}

restart() {
    docker compose down --remove-orphans
    docker compose up -d
    echo "stack started, docker compose logs -f to monitor"
}

case "$1" in
    reload)       reload ;;
    restart)      restart ;;
    import)       import_background "$@" ;;
    update)       shift; update "$@" ;;
    init-elevation) shift; manage_py init-elevation --download "$@" ;;
    key-add)      shift; key_add "$@" ;;
    *)            manage_py "$@" ;;
esac
