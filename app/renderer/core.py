"""Map-object lifecycle and the `render_tile` contract.

`render_tile` is the narrow interface everything above builds against:
theme + bbox (already in the target CRS) + format -> encoded bytes. Tile
and bbox maths, CRS choice and caching all live outside it. A tile is
`TILE_SIZE` square; a WMS GetMap passes its own size, and the borrowed
handle is resized to it and back again by the next tile.

The XML comes from `/data/styles/<schema>/<set>/`, generated by
`renderer.styles`; the pool size and buffer are options.

A pool is keyed by **(theme, TileMatrixSet)**, not by theme alone. The
compiled XML bakes in scale denominators and a `!scale_denominator!` ->
zoom expression, and Mapnik reports that denominator in the units of the
Map's own srs -- so one file cannot serve both a Web Mercator and a
true-metre grid. `renderer.styles` writes one per set and this loads the
one the request addresses; see that module's docstring for the arithmetic
and for what a single file serving both costs.
"""

from __future__ import annotations

import contextlib
import logging
import queue
import threading
import time
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any, Protocol, runtime_checkable

log = logging.getLogger('renderer')

BBox = tuple[float, float, float, float]

#: What the generated XML declares as the Map's own srs, so a request for
#: the native CRS repoints nothing.
DEFAULT_CRS = 'epsg:3857'

#: The TileMatrixSet a caller gets when it names none: the Web Mercator
#: grid, which is the one every XYZ client asks for.
DEFAULT_MATRIX_SET = 'GoogleMapsCompatible'

TILE_SIZE = 256


class MissingStyleError(RuntimeError):
    """A theme's compiled XML is not on disk.

    Loud and specific on purpose: `manage.py compile-styles` owns producing this
    file, and a missing one must never fall back to some other style.
    """


class ThemeNotFoundError(RuntimeError):
    """A render was asked for a theme that was never preloaded.

    Distinct from MissingStyleError so a caller can tell "unknown theme"
    from "the XML was missing when we tried".
    """


@runtime_checkable
class MapnikBackend(Protocol):
    """Everything the registry needs from Mapnik.

    Kept tiny so the pool logic can be tested against a fake -- those
    tests then need neither libmapnik nor a database.
    """

    def load_map(self, xml_path: Path, width: int, height: int, buffer_size: int) -> Any: ...

    def render(self, handle: Any, bbox: BBox, fmt: str, crs: str,
               size: tuple[int, int]) -> bytes: ...


#: Mapnik's encoder names for the canonical short formats the rest of the
#: system uses. `jpg` is the whole reason this exists: every layer above
#: spells it `jpg` (one spelling per format, so a cache key and a
#: Content-Type cannot disagree), and `Image.to_string('jpg')` raises
#: `RuntimeError: unknown file type: jpg` -- Mapnik wants `jpeg`, and passing
#: the format straight through fails only once something asks for a JPEG.
#: `png` is 8-bit paletted:
#: the styles draw an opaque background in flat colours, so 256 colours
#: look the same as RGBA at 40 % of the size and half the encode time
#: (measured on `li`).
MAPNIK_ENCODER = {
    'png': 'png8',
    'jpg': 'jpeg',
}


def encoder_for(fmt: str) -> str:
    """The Mapnik encoder name for a canonical short format.

    An unknown format passes through, so a deployment can ask for one of
    Mapnik's parameterised encoders (`png256`, `jpeg80`) without this table
    having to know about it. It fails at `to_string` if Mapnik disagrees,
    which is the right place.
    """
    return MAPNIK_ENCODER.get(fmt, fmt)


#: Where the image's fonts are. Mapnik finds only the faces its wheel bundles
#: on its own; everything else has to be registered from here.
FONT_DIR = '/usr/share/fonts'


class RealMapnikBackend:
    """The real bindings. `import mapnik` stays inside the methods so that
    importing this module never requires libmapnik."""

    _fonts_registered = False

    def load_map(self, xml_path: Path, width: int, height: int, buffer_size: int) -> Any:
        import mapnik

        self._register_fonts(mapnik)
        handle = mapnik.Map(width, height)
        mapnik.load_map(handle, str(xml_path), True)   # strict
        # The bbox exactly as asked, even where its aspect differs from the
        # image's: a WMS client places the image on that bbox, and the
        # default (grow the bbox) would shift it. A square tile is unaffected.
        handle.aspect_fix_mode = mapnik.aspect_fix_mode.RESPECT
        return handle

    @classmethod
    def _register_fonts(cls, mapnik) -> None:
        """Once per process. Mapnik does not find system fonts on its own,
        and a style naming an unregistered face fails at load."""
        if not cls._fonts_registered:
            mapnik.register_fonts(FONT_DIR)
            cls._fonts_registered = True

    def render(self, handle: Any, bbox: BBox, fmt: str, crs: str,
               size: tuple[int, int]) -> bytes:
        import mapnik

        # `.srs` and the size are plain mutable state: this repoints an
        # already-parsed Map at the CRS and size this request wants, it does
        # not reparse anything. Safe only because the caller holds the handle
        # exclusively for the whole render.
        handle.srs = crs
        if (handle.width, handle.height) != size:
            handle.resize(*size)
        handle.zoom_to_box(mapnik.Box2d(*bbox))
        image = mapnik.Image(handle.width, handle.height)
        mapnik.render(handle, image)
        # `to_string`, not `tostring`: renamed in Mapnik 4, and a test
        # that mocks at the backend boundary cannot catch it.
        return image.to_string(encoder_for(fmt))


class MapRegistry:
    """The per-theme pool of preloaded Mapnik Map objects.

    A *pool* rather than one Map per theme because rendering mutates the
    handle in place (`srs`, `zoom_to_box`), so one handle serves one
    render at a time. Holding several lets that many tiles of the same
    theme render at once, which is the case that matters: Mapnik releases
    the GIL while rendering, and a browser fills a viewport from one
    theme.
    """

    def __init__(self, backend: MapnikBackend | None = None, *,
                 tile_size: int = TILE_SIZE, buffer_size: int = 64,
                 pool_size: int = 4, db_pool_size: int = 40) -> None:
        self._backend = backend or RealMapnikBackend()
        self._tile_size = tile_size
        self._buffer_size = buffer_size
        self._pool_size = pool_size
        # Each retry evicts one dead pooled connection, so one more than
        # the pool holds clears it.
        self.lost_connection_retries = db_pool_size + 1
        self._pools: dict[tuple[str, str], queue.Queue] = {}
        # How many times each theme has been loaded. The web module turns
        # (theme, generation) into an ETag for unversioned tiles: a style
        # recompile is the only thing that changes what one tile address
        # renders.
        self._generations: dict[tuple[str, str], int] = {}
        self._lock = threading.Lock()

    def load_theme(self, theme: str, xml_path: Path,
                   matrix_set: str = DEFAULT_MATRIX_SET) -> None:
        """Parse one theme's XML for one TileMatrixSet into a fresh pool.

        Every handle is built before the new pool is published, so a
        reload that fails partway leaves the working pool in place rather
        than taking the theme down.
        """
        if not xml_path.is_file():
            raise MissingStyleError(
                f'no compiled XML for theme {theme!r} in set {matrix_set!r} at '
                f'{xml_path}. Run `manage.py compile-styles`; refusing to fall back to '
                f'another style.')
        log.info('loading map %s', xml_path)
        handles = [self._backend.load_map(xml_path, self._tile_size, self._tile_size,
                                          self._buffer_size)
                   for _ in range(self._pool_size)]
        pool: queue.Queue = queue.Queue(maxsize=self._pool_size)
        for handle in handles:
            pool.put(handle)
        key = (theme, matrix_set)
        with self._lock:
            self._pools[key] = pool
            self._generations[key] = self._generations.get(key, 0) + 1

    def preload(self, themes, xml_path_for: Callable[..., Path],
                matrix_set: str = DEFAULT_MATRIX_SET) -> list[str]:
        """Load every theme for one set, skipping the ones that fail.

        A theme that cannot load is logged, not fatal. That is what lets
        the stack start before anything has been imported: Mapnik opens
        each layer's datasource while parsing, so against an empty
        database every theme raises. Failing hard there is a restart loop
        that no `docker exec` can get into to fix. A theme that is not loaded still
        fails loudly per request, through ThemeNotFoundError.
        """
        loaded = []
        for theme in themes:
            try:
                self.load_theme(theme, xml_path_for(theme, matrix_set), matrix_set)
            except Exception:
                log.warning('theme %r (%s) failed to load and will not be served',
                            theme, matrix_set, exc_info=True)
            else:
                loaded.append(theme)
        return loaded

    @contextlib.contextmanager
    def _checkout(self, theme: str, matrix_set: str) -> Iterator[Any]:
        """Borrow one handle for one render. Blocks while all are busy."""
        key = (theme, matrix_set)
        try:
            pool = self._pools[key]
        except KeyError as exc:
            raise ThemeNotFoundError(
                f'theme {theme!r} in set {matrix_set!r} was never loaded; '
                f'loaded: {self.loaded()!r}. Themes load at startup -- '
                f'rendering never loads XML on demand.'
            ) from exc

        handle = pool.get()
        try:
            yield handle
        finally:
            # A reload may have swapped in a whole new pool while this
            # render was in flight. Returning a handle from the old XML
            # would both overfill the new queue and resurrect the
            # pre-reload style, so drop it instead.
            if self._pools.get(key) is pool:
                pool.put(handle)

    def loaded(self, matrix_set: str | None = None) -> list[str]:
        """Theme names, for one set or (with none) every loaded pair."""
        if matrix_set is None:
            return sorted(f'{theme}/{set_}' for theme, set_ in self._pools)
        return sorted(theme for theme, set_ in self._pools if set_ == matrix_set)

    def generation(self, theme: str, matrix_set: str = DEFAULT_MATRIX_SET) -> int:
        return self._generations.get((theme, matrix_set), 0)

    def render(self, theme: str, bbox: BBox, fmt: str, crs: str = DEFAULT_CRS,
               matrix_set: str = DEFAULT_MATRIX_SET, steps=None,
               size: tuple[int, int] | None = None) -> bytes:
        """Render one tile, riding out connections a database restart killed.

        Mapnik's PostGIS plugin keeps its own pool of connections, one pool
        per connection string -- all layers share it -- holding up to
        `db.mapnik_pool_size` (`max_size` in the XML). After Postgres restarts, every pooled
        connection still looks open until a query on it fails; the plugin
        then drops it. So without a retry the first render after a restart
        fails with "server closed the connection unexpectedly" and a 500.

        A failure of that kind is retried: each retry either succeeds or
        evicts one more dead connection, so `lost_connection_retries`
        attempts clear a full pool within one request. Only that failure --
        a database that is still *down* says "connection refused", fails
        fast, and is not retried.

        `steps` (a `lib.timing.Steps`) gets the wait for a handle and the
        render apart: a tile that queued behind `map_pool_size` renders of
        the same theme looks, in the access log, like a slow render.
        """
        size = size or (self._tile_size, self._tile_size)
        started = time.perf_counter()
        with self._checkout(theme, matrix_set) as handle:
            if steps is not None:
                steps.add('wait', (time.perf_counter() - started) * 1000)
            for attempt in range(self.lost_connection_retries + 1):
                try:
                    if steps is None:
                        return self._backend.render(handle, bbox, fmt, crs, size)
                    with steps.step('render'):
                        return self._backend.render(handle, bbox, fmt, crs, size)
                except RuntimeError as exc:
                    if attempt == self.lost_connection_retries or not lost_connection(exc):
                        raise
                    log.warning('render of %s hit a dropped database connection; '
                                'retrying (%d)', theme, attempt + 1)
        raise AssertionError('unreachable')   # the loop returns or raises


#: What libpq says about a pooled connection the server has gone away from.
_LOST_CONNECTION = (
    'server closed the connection unexpectedly',
    'terminating connection due to administrator command',
    'no connection to the server',
)


def lost_connection(exc: BaseException) -> bool:
    message = str(exc)
    return any(marker in message for marker in _LOST_CONNECTION)


_registry: MapRegistry | None = None


def styles_dir(schema: str | None = None) -> Path:
    from lib import config, db

    schema = schema or db.active_schema()
    return Path(config.opt('data_dir', '/data')) / 'styles' / schema


def xml_path_for(theme: str, schema: str | None = None,
                 matrix_set: str = DEFAULT_MATRIX_SET) -> Path:
    return styles_dir(schema) / matrix_set / f'{theme}.xml'


def available_themes(schema: str | None = None,
                     matrix_set: str = DEFAULT_MATRIX_SET) -> list[str]:
    """Theme names with compiled XML on disk for one set, limited to what
    `serve_palettes` and `serve_details` select.

    One set, because the answer is the same for all of them -- the
    generator writes every theme for every set or fails before writing
    anything -- and a caller asking "which themes are there" means the
    names, not the names times the grids.

    Filtered here and not only when compiling, because XML from an earlier
    compile with a wider selection stays on disk until `manage.py compile-styles`
    runs again, and everything that loads, lists, serves or pre-caches a
    theme asks this.
    """
    directory = styles_dir(schema) / matrix_set
    if not directory.is_dir():
        return []
    return sorted(path.stem for path in directory.glob('*.xml') if _served(path.stem))


def _served(theme: str) -> bool:
    from lib import config

    palette, _, detail = theme.partition('_')
    palettes = config.opt('serve_palettes')
    details = config.opt('serve_details')
    return ((not palettes or palette in palettes)
            and (not details or detail in details))


def get_registry() -> MapRegistry:
    """The process-wide registry: Map objects loaded once and reused."""
    global _registry
    if _registry is None:
        from lib import config

        _registry = MapRegistry(buffer_size=int(config.opt('buffer_px', 64)),
                                pool_size=int(config.opt('map_pool_size', 4)),
                                db_pool_size=int(config.opt('db.mapnik_pool_size', 40)))
    return _registry


def render_tile(theme: str, bbox: BBox, fmt: str, crs: str = DEFAULT_CRS,
                matrix_set: str = DEFAULT_MATRIX_SET, steps=None,
                size: tuple[int, int] | None = None) -> bytes:
    """Render one tile, or a `size` (width, height) image. `bbox` is already in `crs`.

    `crs` repoints the Map; `matrix_set` picks which compiled XML to
    repoint. They are two facts, not one: the XML's scale arithmetic
    belongs to the grid, and a grid is what a request addresses.
    """
    return get_registry().render(theme, bbox, fmt, crs, matrix_set, steps, size)


def preload_all(schema: str | None = None,
                matrix_sets: list[str] | None = None) -> dict[str, list[str]]:
    """Load every served theme, for every served TileMatrixSet.

    Every caller that starts a server needs this loop, and each one that
    wrote it by hand got the callback's arity wrong -- `preload` passes
    `(theme, matrix_set)` and a one-argument lambda raises, which `preload`
    catches and logs per theme. The server then starts, reports its themes,
    and answers every tile with `ThemeNotFoundError`. Loud in the log,
    invisible in the health check, so it belongs here once.

    Returns {matrix set: themes loaded}, which is also what the reload hook
    reports back.
    """
    from lib import db
    from renderer import matrix

    schema = schema or db.active_schema()
    if matrix_sets is None:
        matrix_sets = sorted(tms.identifier for tms in matrix.load().values())

    registry = get_registry()
    out: dict[str, list[str]] = {}
    for matrix_set in matrix_sets:
        themes = available_themes(schema, matrix_set)
        out[matrix_set] = registry.preload(
            themes,
            lambda theme, set_name, s=schema: xml_path_for(theme, s, set_name),
            matrix_set)
    return out
