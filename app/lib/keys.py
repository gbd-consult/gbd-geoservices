"""The API keys and what they were used for, in the schema `service`.

    service.api_key     one row per key: name, customer, the key's SHA-256,
                        scopes, referrers, rate, expiry, whether disabled
    service.key_usage   one row per key and month: tiles and search requests,
                        and errors -- the key's requests answered 400 or above
    service.key_request one row per trial key asked for on the landing page:
                        e-mail address, organisation, time. Deleted when the
                        operator has dealt with it (`request_done`), and by
                        `stats.purge` after `stats.MAX_RETENTION_DAYS` at most

A key is never stored, only its SHA-256, so the database, a backup or a
dump of it opens nothing. Keys are generated by one script only,
`scripts/vaultwarden-send.sh`, which hands the key to its customer as a
Vaultwarden Send; `generate` runs it, for `manage.py key-add` in the
one-off `keys` container, which registers the key here. Nothing in this
package generates one itself. A plain hash, not a slow one,
because a generated key is 256 random bits and no wordlist reaches it; a
key registered by hand (`key-register`) is only as strong as whoever made
it.

The schema outlives every import, as `elevation` does. The app only reads
it and adds usage; `ensure` -- creating the schema -- is run by the
management commands that write keys, so the app needs no DDL rights, and a
database where no key was ever added has no table, which `load` reads as no
keys (`web/auth.py`: open access).

Usage is counted per calendar month in UTC.

A key request is only a request: the form cannot issue a key, since keys
come from `vaultwarden-send.sh` alone. The operator lists the requests,
issues a trial key with `key-add --trial` and marks the request done.
"""

from __future__ import annotations

import csv
import datetime
import hashlib
import subprocess
from collections.abc import Iterable
from pathlib import Path
from typing import TextIO

from psycopg import sql

from lib import db

SCHEMA = 'service'

#: The scopes a key can carry. `tiles` and `search` are counted, each a usage
#: column beside `errors`; `devtools` opens the viewer and is not counted.
SCOPES = ('tiles', 'search', 'devtools')

#: What a key that names no scope carries: the API, not the viewer. The
#: viewer is ours, and a customer's key added without `--scopes` must not open it.
DEFAULT_SCOPES = ('tiles', 'search')

#: How long `add(..., trial=True)` makes a key valid.
TRIAL_DAYS = 30

#: Where keys are made; scripts/ lies beside lib/ in the image as in the checkout.
SEND_SCRIPT = Path(__file__).resolve().parent.parent / 'scripts' / 'vaultwarden-send.sh'


def digest(key: str) -> str:
    """The stored form of a key. UTF-8, so any string a client sends hashes."""
    return hashlib.sha256(key.encode('utf-8')).hexdigest()


def month_of(day: datetime.date) -> datetime.date:
    return day.replace(day=1)


def today() -> datetime.date:
    return datetime.datetime.now(datetime.UTC).date()


def _t(name: str) -> sql.Identifier:
    return sql.Identifier(SCHEMA, name)


def ensure(conn) -> None:
    conn.execute(sql.SQL('create schema if not exists {}').format(sql.Identifier(SCHEMA)))
    conn.execute(sql.SQL("""
        create table if not exists {key} (
            id        serial primary key,
            name      text not null unique,
            customer  text,
            hash      text not null unique,
            scopes    text[] not null default '{{}}',
            referrers text[] not null default '{{}}',
            rate      integer,
            expires   date,
            disabled  boolean not null default false,
            created   timestamptz not null default now()
        )""").format(key=_t('api_key')))
    conn.execute(sql.SQL("""
        create table if not exists {usage} (
            key_id  integer not null references {key} (id),
            month   date not null,
            tiles   bigint not null default 0,
            search  bigint not null default 0,
            errors  bigint not null default 0,
            primary key (key_id, month)
        )""").format(usage=_t('key_usage'), key=_t('api_key')))
    conn.execute(sql.SQL("""
        create table if not exists {} (
            id            serial primary key,
            ts            timestamptz not null default now(),
            email         text not null,
            organisation  text
        )""").format(_t('key_request')))
    conn.commit()


def generate(name: str) -> tuple[str, str]:
    """A new key and the link of the Vaultwarden Send that carries it.

    Only the script's stdout is read: the key, then the link. bw's prompts,
    when the BW_* variables are unset, go to the terminal.
    """
    out = subprocess.run(['bash', str(SEND_SCRIPT), '--generate-key', '-n', f'API-Key {name}'],
                         stdout=subprocess.PIPE, text=True, check=True).stdout.split()
    if len(out) != 2:
        raise RuntimeError('vaultwarden-send.sh returned no key and link')
    return out[0], out[1]


def load() -> list[dict]:
    """Every key record, as a dict per row.

    No table is no keys: a database no key was ever added to.
    """
    with db.connection() as conn:
        if conn.execute('select to_regclass(%s)', (f'{SCHEMA}.api_key',)).fetchone()[0] is None:
            return []
        cur = conn.execute(sql.SQL(
            'select id, name, hash, scopes, referrers, rate, expires, disabled'
            ' from {} order by id').format(_t('api_key')))
        names = [column.name for column in cur.description]
        return [dict(zip(names, row, strict=True)) for row in cur.fetchall()]


def add(name: str, key: str, *, customer: str | None = None,
        scopes: Iterable[str] = (), referrers: Iterable[str] = (), rate: int | None = None,
        expires: datetime.date | None = None, trial: bool = False) -> None:
    """Register a key by its digest."""
    scopes = list(scopes)
    unknown = set(scopes) - set(SCOPES)
    if unknown:
        raise ValueError(f'unknown scope(s) {sorted(unknown)}; valid: {list(SCOPES)}')
    if trial:
        if expires is not None:
            raise ValueError('a trial key has its own expiry; give one or the other')
        expires = today() + datetime.timedelta(days=TRIAL_DAYS)
    if not key:
        raise ValueError('no key given')
    with db.connection() as conn:
        ensure(conn)
        conn.execute(sql.SQL(
            'insert into {} (name, customer, hash, scopes, referrers, rate, expires)'
            ' values (%s, %s, %s, %s, %s, %s, %s)').format(_t('api_key')),
            (name, customer, digest(key), scopes, list(referrers), rate, expires))
        conn.commit()


def set_disabled(name: str, disabled: bool) -> bool:
    """Disable or enable a key by name; False if there is no such key."""
    with db.connection() as conn:
        ensure(conn)
        cur = conn.execute(sql.SQL('update {} set disabled = %s where name = %s').format(
            _t('api_key')), (disabled, name))
        conn.commit()
        return cur.rowcount == 1


def listing() -> list[tuple]:
    """Every key without its hash, for an operator to read."""
    with db.connection() as conn:
        ensure(conn)
        return conn.execute(sql.SQL(
            'select name, customer, scopes, referrers, rate, expires, disabled, created'
            ' from {} order by name').format(_t('api_key'))).fetchall()


def request_add(email: str, organisation: str | None, limit: int) -> int | None:
    """Store a trial key request; its id, or None with `limit` requests open.

    An address already waiting is not stored again: its request's id comes
    back, so repeating it takes no second place under `limit`.
    """
    with db.connection() as conn:
        ensure(conn)
        waiting = conn.execute(sql.SQL('select id from {} where lower(email) = lower(%s)').format(
            _t('key_request')), (email,)).fetchone()
        if waiting:
            return waiting[0]
        if conn.execute(sql.SQL('select count(*) from {}').format(
                _t('key_request'))).fetchone()[0] >= limit:
            return None
        request_id = conn.execute(sql.SQL(
            'insert into {} (email, organisation) values (%s, %s) returning id').format(
            _t('key_request')), (email, organisation)).fetchone()[0]
        conn.commit()
        return request_id


def requests() -> list[tuple]:
    """The open key requests: id, time, e-mail address, organisation."""
    with db.connection() as conn:
        ensure(conn)
        return conn.execute(sql.SQL('select id, ts, email, organisation from {} order by id')
                            .format(_t('key_request'))).fetchall()


def request_done(request_id: int) -> bool:
    """Delete a request once dealt with; False if there is no such request."""
    with db.connection() as conn:
        ensure(conn)
        cur = conn.execute(sql.SQL('delete from {} where id = %s').format(_t('key_request')),
                           (request_id,))
        conn.commit()
        return cur.rowcount == 1


def purge_requests(conn, cutoff: datetime.date) -> None:
    """Delete the key requests from before `cutoff`, e-mail addresses with them."""
    if conn.execute('select to_regclass(%s)', (f'{SCHEMA}.key_request',)).fetchone()[0] is not None:
        conn.execute(sql.SQL('delete from {} where ts < %s').format(_t('key_request')),
                     (cutoff.isoformat(),))


def add_usage(counts: dict[tuple[int, datetime.date], dict[str, int]]) -> None:
    """Add {(key id, month): {tiles|search|errors: requests}} to the monthly totals."""
    rows = [(key_id, month, columns.get('tiles', 0), columns.get('search', 0),
             columns.get('errors', 0))
            for (key_id, month), columns in counts.items()]
    if not rows:
        return
    with db.connection() as conn:
        conn.cursor().executemany(sql.SQL("""
            insert into {usage} as u (key_id, month, tiles, search, errors)
            values (%s, %s, %s, %s, %s)
            on conflict (key_id, month) do update
            set tiles = u.tiles + excluded.tiles, search = u.search + excluded.search,
                errors = u.errors + excluded.errors
            """).format(usage=_t('key_usage')), rows)
        conn.commit()


def export_usage(month: datetime.date, out: TextIO) -> int:
    """Write the month's usage per key as CSV; return the number of keys.

    Every key appears, a key with no requests with zeros, so the invoice
    run sees a customer who had nothing to pay for rather than missing them.
    `;`-separated, the form a German spreadsheet opens without asking.
    """
    with db.connection() as conn:
        ensure(conn)
        rows = conn.execute(sql.SQL("""
            select k.name, coalesce(k.customer, ''), coalesce(u.tiles, 0), coalesce(u.search, 0),
                   coalesce(u.errors, 0)
            from {key} k left join {usage} u on u.key_id = k.id and u.month = %s
            order by k.name
            """).format(key=_t('api_key'), usage=_t('key_usage')), (month_of(month),)).fetchall()
    writer = csv.writer(out, delimiter=';', lineterminator='\n')
    writer.writerow(['key', 'customer', 'month', 'tiles', 'search', 'errors'])
    label = f'{month:%Y-%m}'
    for name, customer, tiles, search, errors in rows:
        writer.writerow([name, customer, label, tiles, search, errors])
    return len(rows)
